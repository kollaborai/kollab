// Writes the plugin SDK declarations that the bundled Hello web example type-checks against.
// The contract is copied from the host's own types in src/plugins/sdk.ts, so the two cannot drift:
// `--check` fails when the committed declarations are stale.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const frontend = new URL("../", import.meta.url);
const sdk = await readFile(new URL("src/plugins/sdk.ts", frontend), "utf8");

// The contract types: from the OpenTarget doc comment up to the app's own components.
const contractStart = sdk.indexOf("/** Where a menu row, a notice button or `k.navigate` goes. */");
const contractEnd = sdk.indexOf("/** The app's own components");
// PluginApi and PluginSetup: from the k doc comment up to the definePlugin doc comment.
const apiStart = sdk.indexOf("/** `k`: a plugin's handle on the app. */");
const apiEnd = sdk.indexOf("/** What `web/dist/index.js` default-exports. */");
const uiBody = sdk.match(/export const ui = \{([\s\S]*?)\n\};/)?.[1];
if (contractStart < 0 || contractEnd <= contractStart || apiStart < 0 || apiEnd <= apiStart || !uiBody) {
  throw new Error("Cannot locate the plugin SDK declarations in src/plugins/sdk.ts");
}
const uiNames = uiBody.split(",").map(name => name.trim()).filter(Boolean);
if (uiNames.some(name => !/^[A-Za-z_$][\w$]*$/.test(name))) throw new Error("Cannot parse the ui component names");

const declaration = [
  "// Generated by frontend/scripts/generate-plugin-types.mjs from src/plugins/sdk.ts. Do not edit.",
  'declare module "@kollab/plugin" {',
  'import type { ComponentType } from "react";',
  sdk.slice(contractStart, contractEnd).trim(),
  "/** The app's own components, so a plugin looks like kollab. */",
  `export const ui: { ${uiNames.map(name => `${name}: ComponentType<any>`).join("; ")} };`,
  sdk.slice(apiStart, apiEnd).trim(),
  "/** What `web/dist/index.js` default-exports. */",
  "export function definePlugin(setup: PluginSetup): PluginSetup;",
  "}",
  "",
].join("\n");

const target = new URL("../../../bundles/plugins/hello/web/src/kollab-plugin.d.ts", frontend);
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile(target, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (current !== declaration) {
    console.error(`Generated plugin declarations are stale: ${fileURLToPath(target)}`);
    console.error("Run: node packages/kollabor-webui/frontend/scripts/generate-plugin-types.mjs");
    process.exit(1);
  }
} else {
  await writeFile(target, declaration);
}
