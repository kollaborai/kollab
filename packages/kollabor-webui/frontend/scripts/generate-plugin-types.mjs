// Generate the portable plugin SDK contract from the host's authoritative types.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const frontend = new URL("../", import.meta.url);
const sdk = await readFile(new URL("src/plugins/sdk.ts", frontend), "utf8");
const api = await readFile(new URL("src/api.ts", frontend), "utf8");
const ui = await readFile(new URL("src/plugins/ui.tsx", frontend), "utf8");
const start = sdk.indexOf("export type PluginOpen");
const end = sdk.indexOf("/** Type-check", start);
const session = api.match(/^export type Session = \{[\s\S]*?^\};/m)?.[0];
const uiBody = ui.match(/export const pluginUI = \{([\s\S]*?)\n\};/)?.[1];
if (start < 0 || end < 0 || !session || !uiBody) throw new Error("Cannot locate plugin SDK declarations");
const uiNames = uiBody.split(",").map(name => name.trim().split(":", 1)[0].trim()).filter(Boolean);
if (uiNames.some(name => !/^[A-Za-z_$][\w$]*$/.test(name))) throw new Error("Cannot parse shared UI names");
const declaration = `// Generated by frontend/scripts/generate-plugin-types.mjs. Do not edit.\n` +
  `declare module "@kollab/plugin" {\nimport type { ComponentType } from "react";\n` +
  `${session}\nexport type PluginUi = { ${uiNames.map(name => `${name}: ComponentType<any>`).join("; ")} };\n` +
  `${sdk.slice(start, end).trim()}\n` +
  `export function definePlugin(activate: (k: PluginContext) => void | Promise<void>): (k: PluginContext) => void | Promise<void>;\n}\n`;
const target = new URL("../../../bundles/plugins/hello/web/src/kollab-plugin.d.ts", frontend);
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8");
  if (current !== declaration) throw new Error(`Generated plugin declarations are stale: ${fileURLToPath(target)}`);
} else {
  await writeFile(target, declaration);
}
