/**
 * Pure model for the System Prompts page: grouping, ordering, badges, and
 * provenance. Kept free of React and browser APIs so the
 * vitest suite can drive every decision the page makes.
 */
import type {
  PromptEntry,
  PromptSection,
  PromptSectionKind,
  PromptSource,
} from "@/prompts-api";

export type PromptGroup = {
  source: PromptSource;
  label: string;
  prompts: PromptEntry[];
};

const SOURCE_LABEL: Record<PromptSource, string> = {
  bundled: "Bundled",
  global: "Global",
  local: "Project",
};

/** Bundled first, then global, then project; alphabetical within each. */
export function groupPrompts(prompts: readonly PromptEntry[]): PromptGroup[] {
  const byName = (a: PromptEntry, b: PromptEntry) =>
    a.name.localeCompare(b.name) || a.bundle.localeCompare(b.bundle);
  return (["bundled", "global", "local"] as const)
    .map((source) => ({
      source,
      label: SOURCE_LABEL[source],
      prompts: prompts.filter((prompt) => prompt.source === source).sort(byName),
    }))
    .filter((group) => group.prompts.length > 0);
}

/** Server order wins; key breaks ties so rows never jitter. */
export function sortSections(
  sections: readonly PromptSection[],
): PromptSection[] {
  return [...sections].sort(
    (a, b) => a.order - b.order || a.key.localeCompare(b.key),
  );
}

export function isEditable(kind: PromptSectionKind): boolean {
  return kind === "editable";
}

/** Where a read-only section comes from; null for editable sections. */
export function provenanceNote(section: {
  kind: PromptSectionKind;
  source_path: string | null;
}): string | null {
  switch (section.kind) {
    case "generated":
      return `Read-only: generated by the build from ${section.source_path ?? "the server"}. Edit the source, not this section.`;
    case "runtime":
      return `Read-only: provided at runtime from ${section.source_path ?? "the server"}.`;
    default:
      return null;
  }
}

/** Trajectory-style kind colors: one hue per section kind. */
export function kindClass(kind: PromptSectionKind): string {
  switch (kind) {
    case "editable":
      return "text-emerald-700 dark:text-emerald-300";
    case "generated":
      return "text-amber-700 dark:text-amber-300";
    case "runtime":
      return "text-sky-700 dark:text-sky-300";
  }
}

export function tokensTotal(sections: readonly { tokens: number }[]): number {
  return sections.reduce((total, section) => total + (section.tokens || 0), 0);
}

/** True when the editor text differs from the section's stored content. */
export function isDirty(draft: string, stored: string | null): boolean {
  return draft !== (stored ?? "");
}
