// Run: npx vitest run tests/prompts-page.test.ts
// The System Prompts page: its typed client against fixture transports, its
// pure model decisions, and the rendered three-panel view (SSR) over fixtures.

import { describe, expect, it } from "vitest";
import { renderToString } from "react-dom/server";
import { jsx } from "react/jsx-runtime";

import { PromptsApi, PromptsApiError } from "../src/prompts-api";
import type { PromptSection } from "../src/prompts-api";
import {
  groupPrompts,
  isDirty,
  kindClass,
  provenanceNote,
  sectionKeyFromTitle,
  sortSections,
  tokensTotal,
} from "../src/components/prompts/prompts-model";
import { PromptsView } from "../src/components/prompts/PromptsPage";
import {
  FIXTURE_CONTENT,
  FIXTURE_PREVIEW,
  FIXTURE_PROMPTS,
  FIXTURE_SECTIONS,
  fixtureTransport,
} from "./fixtures/prompts";

describe("PromptsApi", () => {
  it("lists prompts from GET /prompts", async () => {
    const fixture = fixtureTransport();
    const api = new PromptsApi(fixture.transport);
    const result = await api.listPrompts();
    expect(result.prompts).toEqual(FIXTURE_PROMPTS);
    expect(fixture.calls[0]).toMatchObject({ path: "/prompts", init: {} });
  });

  it("lists sections under the bundle's encoded path", async () => {
    const fixture = fixtureTransport();
    const api = new PromptsApi(fixture.transport);
    const result = await api.listSections("coder");
    expect(result.sections).toEqual(FIXTURE_SECTIONS);
    expect(fixture.calls[0].path).toBe("/prompts/coder/sections");
  });

  it("encodes bundle and key path segments", async () => {
    const fixture = fixtureTransport();
    const api = new PromptsApi(fixture.transport);
    await expect(
      api.getSection("my agent", "hook system"),
    ).rejects.toBeInstanceOf(PromptsApiError);
    expect(fixture.calls[0].path).toBe(
      "/prompts/my%20agent/sections/hook%20system",
    );
  });

  it("saves an override with PUT and a JSON content body", async () => {
    const fixture = fixtureTransport();
    const api = new PromptsApi(fixture.transport);
    await api.saveSection("coder", "identity", "Rewritten identity.\n");
    expect(fixture.calls[0]).toMatchObject({
      path: "/prompts/coder/sections/identity",
    });
    expect(fixture.calls[0].init.method).toBe("PUT");
    expect(JSON.parse(String(fixture.calls[0].init.body))).toEqual({
      content: "Rewritten identity.\n",
    });
    expect(fixture.saved["coder/identity"]).toBe("Rewritten identity.\n");
  });

  it("deletes an override with DELETE on the same path", async () => {
    const fixture = fixtureTransport();
    const api = new PromptsApi(fixture.transport);
    await api.deleteOverride("coder", "output-style");
    expect(fixture.calls[0].init.method).toBe("DELETE");
    expect(fixture.calls[0].path).toBe("/prompts/coder/sections/output-style");
    expect(fixture.deleted).toEqual(["coder/output-style"]);
  });

  it("fetches the rendered preview", async () => {
    const fixture = fixtureTransport();
    const api = new PromptsApi(fixture.transport);
    const preview = await api.preview("coder");
    expect(preview).toEqual(FIXTURE_PREVIEW);
    expect(fixture.calls[0].path).toBe("/prompts/coder/preview");
  });

  it("propagates server errors with their status", async () => {
    const api = new PromptsApi(fixtureTransport().transport);
    await expect(api.getSection("coder", "missing")).rejects.toThrow(
      /Section not found/,
    );
  });
});

describe("prompts model", () => {
  it("groups bundled before user-installed, alphabetical inside each", () => {
    const groups = groupPrompts(FIXTURE_PROMPTS);
    expect(groups.map((group) => group.source)).toEqual(["bundled", "user"]);
    expect(groups[0].prompts.map((prompt) => prompt.name)).toEqual([
      "Coder",
      "Research",
    ]);
    expect(groups[0].label).toBe("Bundled");
    expect(groups[1].label).toBe("User installed");
  });

  it("sorts sections by server order, key as tie-break", () => {
    const ordered = sortSections(FIXTURE_SECTIONS);
    expect(ordered.map((section) => section.key)).toEqual([
      "identity",
      "skills",
      "hooks",
      "output-style",
    ]);
  });

  it("marks only editable sections as editable", () => {
    const byKey = (key: string) =>
      FIXTURE_SECTIONS.find((section) => section.key === key) as PromptSection;
    expect(provenanceNote(byKey("identity"))).toBeNull();
    expect(provenanceNote(byKey("skills"))).toContain("generated by the build");
    expect(provenanceNote(byKey("skills"))).toContain(byKey("skills").source_path);
    expect(provenanceNote(byKey("hooks"))).toContain("provided at runtime");
    expect(kindClass("editable")).not.toBe(kindClass("generated"));
    expect(kindClass("generated")).not.toBe(kindClass("runtime"));
  });

  it("derives unique slug keys for new sections", () => {
    expect(sectionKeyFromTitle("Output Style", [])).toBe("output-style");
    expect(
      sectionKeyFromTitle("Identity", ["identity", "identity-2"]),
    ).toBe("identity-3");
    expect(sectionKeyFromTitle("  ###  ", [])).toBe("section");
  });

  it("sums server token counts and detects dirty drafts", () => {
    expect(tokensTotal(FIXTURE_SECTIONS)).toBe(84 + 210 + 1337 + 512);
    expect(isDirty("changed", "stored")).toBe(true);
    expect(isDirty("stored", "stored")).toBe(false);
    expect(isDirty("typed", null)).toBe(true);
  });
});

function renderPage() {
  return renderToString(
    jsx(PromptsView, {
      groups: groupPrompts(FIXTURE_PROMPTS),
      loadError: null,
      bundle: "coder",
      sections: sortSections(FIXTURE_SECTIONS),
      selected: "output-style",
      creating: null,
      creatingOpen: false,
      newTitle: "",
      content: FIXTURE_CONTENT["output-style"],
      draft: FIXTURE_CONTENT["output-style"].content,
      previewing: false,
      preview: null,
      busy: false,
      message: { ok: true, text: "Override saved." },
      onNewTitle: () => {},
      onOpenCreate: () => {},
      onBeginCreate: () => {},
      onCancelCreate: () => {},
      onSelectBundle: () => {},
      onSelectSection: () => {},
      onDraftChange: () => {},
      onSave: () => {},
      onDeleteOverride: () => {},
      onTogglePreview: () => {},
    }),
  );
}

describe("PromptsView (rendered)", () => {
  const html = renderPage();

  it("renders the three panels", () => {
    for (const id of ["prompts-page", "prompts-sidebar", "prompts-sections", "prompts-editor"]) {
      expect(html).toContain(`data-testid="${id}"`);
    }
  });

  it("groups the sidebar by bundle source", () => {
    expect(html).toContain("Bundled");
    expect(html).toContain("User installed");
    expect(html).toContain('data-testid="prompt-row"');
    expect(html).toContain('data-bundle="coder"');
    expect(html).toContain('data-bundle="my-agent"');
  });

  it("lists sections with token counts and kind badges in order", () => {
    const rows = html.split('data-testid="section-row"').length - 1;
    expect(rows).toBe(4);
    expect(html).toContain(">84<");
    expect(html).toContain(">1,337<");
    expect(html).toContain(">editable<");
    expect(html).toContain(">generated<");
    expect(html).toContain(">runtime<");
  });

  it("flags the overridden section", () => {
    expect(html).toContain('data-testid="overridden-badge"');
    expect(html).toContain("Override file:");
    expect(html).toContain(".kollab/agents/coder/overrides/output-style.md");
  });

  it("shows the selected editable section in a writable editor", () => {
    expect(html).toContain('data-testid="section-content"');
    expect(html).not.toContain("readOnly=\"\"");
    expect(html).toContain('data-testid="save-section"');
    expect(html).toContain("Save override");
    expect(html).toContain('data-testid="delete-override"');
  });

  it("keeps status feedback visible", () => {
    expect(html).toContain("Override saved.");
  });
});

